package com.personal.marketnote.commerce.port.in.result.order;

import com.personal.marketnote.commerce.domain.order.OrderProduct;
import com.personal.marketnote.commerce.domain.order.OrderProductCreateState;
import com.personal.marketnote.commerce.domain.order.OrderProductSnapshotState;
import com.personal.marketnote.commerce.domain.order.OrderStatus;
import com.personal.marketnote.commerce.port.out.product.result.ProductOptionInfoResult;
import com.personal.marketnote.commerce.port.out.result.product.ProductInfoResult;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

class GetOrderProductResultTest {

    @Test
    @DisplayName("OrderProduct 도메인의 orderProductKey가 결과에 그대로 매핑된다")
    void shouldMapOrderProductKeyFromDomain() {
        // given
        UUID expectedKey = UUID.fromString("018f0000-0000-7000-8000-000000000001");
        OrderProduct orderProduct = OrderProduct.from(OrderProductSnapshotState.builder()
                .orderId(1L)
                .sellerId(10L)
                .pricePolicyId(100L)
                .orderProductKey(expectedKey)
                .quantity(2)
                .unitAmount(50000L)
                .accumulatedPoint(0L)
                .orderStatus(OrderStatus.PAID)
                .build());

        ProductInfoResult productInfo = new ProductInfoResult(
                1L, null, null, "테스트 상품", "테스트 브랜드", null, null, null, List.<ProductOptionInfoResult>of()
        );

        // when
        GetOrderProductResult result = GetOrderProductResult.from(orderProduct, productInfo, OrderStatus.PAID);

        // then
        assertThat(result.orderProductKey()).isEqualTo(expectedKey);
    }

    @Test
    @DisplayName("CreateState로 생성된 OrderProduct의 자동 생성된 orderProductKey도 결과에 매핑된다")
    void shouldMapAutoGeneratedOrderProductKey() {
        // given
        OrderProduct orderProduct = OrderProduct.from(OrderProductCreateState.builder()
                .sellerId(10L)
                .pricePolicyId(100L)
                .quantity(1)
                .unitAmount(50000L)
                .accumulatedPoint(0L)
                .build());

        // when
        GetOrderProductResult result = GetOrderProductResult.from(orderProduct, null, OrderStatus.PAID);

        // then
        assertThat(result.orderProductKey()).isNotNull();
        assertThat(result.orderProductKey()).isEqualTo(orderProduct.getOrderProductKey());
    }

    @Test
    @DisplayName("OrderProduct의 scheduledAutoConfirmAt이 결과에 매핑된다")
    void shouldMapScheduledAutoConfirmAtFromOrderProduct() {
        // given
        LocalDateTime scheduledAutoConfirmAt = LocalDateTime.of(2026, 4, 18, 12, 0);
        OrderProduct orderProduct = OrderProduct.from(OrderProductSnapshotState.builder()
                .orderId(1L)
                .sellerId(10L)
                .pricePolicyId(100L)
                .orderProductKey(UUID.randomUUID())
                .quantity(1)
                .unitAmount(50000L)
                .accumulatedPoint(0L)
                .orderStatus(OrderStatus.DELIVERED)
                .scheduledAutoConfirmAt(scheduledAutoConfirmAt)
                .build());

        // when
        GetOrderProductResult result = GetOrderProductResult.from(orderProduct, null, OrderStatus.DELIVERED);

        // then
        assertThat(result.scheduledAutoConfirmAt()).isEqualTo(scheduledAutoConfirmAt);
    }

    @Test
    @DisplayName("OrderProduct.scheduledAutoConfirmAt이 null이면 결과에서도 null이다")
    void shouldReturnNullScheduledAutoConfirmAtWhenOrderProductHasNone() {
        // given
        OrderProduct orderProduct = OrderProduct.from(OrderProductSnapshotState.builder()
                .orderId(1L)
                .sellerId(10L)
                .pricePolicyId(100L)
                .orderProductKey(UUID.randomUUID())
                .quantity(1)
                .unitAmount(50000L)
                .accumulatedPoint(0L)
                .orderStatus(OrderStatus.PAID)
                .build());

        // when
        GetOrderProductResult result = GetOrderProductResult.from(orderProduct, null, OrderStatus.PAID);

        // then
        assertThat(result.scheduledAutoConfirmAt()).isNull();
    }
}
